-- Схема заказов: заказ и его позиции, история статусов, состояние саги
-- оформления и её отложенные шаги и таймеры. Центральная база системы.
--
-- Внешних ключей на другие базы нет: restaurant_id, customer_id и menu_item_id —
-- копии идентификаторов, целостность обеспечивает приложение. Это плата за
-- принцип «база на сервис».
--
-- Деньги — целые копейки, как в каталоге: суммы между сервисами не должны
-- расходиться из-за округления.

-- ─────────────── Заказы ───────────────
CREATE TABLE IF NOT EXISTS orders (
    id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Человекочитаемый номер для клиента и оператора поддержки. Берётся из
    -- последовательности до вставки: он нужен событиям, которые пишутся той же
    -- транзакцией. Пропуски номеров (повтор формы) допустимы
    order_number          BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    customer_id           UUID        NOT NULL,
    restaurant_id         UUID        NOT NULL,
    -- Конечный автомат: допустимые переходы проверяет домен, здесь — только
    -- допустимые значения. PAID и READY — переходные: заказ проходит их
    -- в той же транзакции, что и следующий шаг, и в них не задерживается.
    -- «Забран» и «в пути» — один статус: о вручении курьеру доставка
    -- сообщает одним событием, отдельного источника для второго перехода нет.
    status                VARCHAR(32) NOT NULL DEFAULT 'CREATED'
                          CHECK (status IN ('CREATED', 'PENDING_PAYMENT', 'PAID',
                                            'AWAITING_RESTAURANT', 'COOKING', 'READY',
                                            'ASSIGNING_COURIER', 'IN_TRANSIT',
                                            'DELIVERED', 'CANCELLED')),
    delivery_address_text VARCHAR(500) NOT NULL,
    delivery_location     GEOGRAPHY(Point, 4326) NOT NULL,
    -- Точка выдачи из каталога на момент оформления: доставка к каталогу не ходит
    pickup_location       GEOGRAPHY(Point, 4326),
    -- Контакт для курьера (ORD-1). Персональные данные: в журнал не пишутся
    contact_phone         VARCHAR(32),
    items_amount          INTEGER NOT NULL CHECK (items_amount >= 0),
    delivery_fee          INTEGER NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    service_fee           INTEGER NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
    discount_amount       INTEGER NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount          INTEGER NOT NULL CHECK (total_amount > 0),
    comment               VARCHAR(1000),
    expected_cooking_min  SMALLINT CHECK (expected_cooking_min IS NULL OR expected_cooking_min > 0),
    -- Ключ идемпотентности от клиента (ORD-4): повторная отправка формы
    -- ловится конфликтом уникального индекса, а не предварительной выборкой
    idempotency_key       VARCHAR(100) NOT NULL,
    placed_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    confirmed_at          TIMESTAMPTZ,
    ready_at              TIMESTAMPTZ,
    picked_up_at          TIMESTAMPTZ,
    delivered_at          TIMESTAMPTZ,
    cancelled_at          TIMESTAMPTZ,
    cancel_reason         VARCHAR(16)
                          CHECK (cancel_reason IN ('CUSTOMER', 'RESTAURANT', 'TIMEOUT',
                                                   'OPERATOR', 'TECHNICAL', 'PAYMENT_FAILED')),
    cancel_comment        VARCHAR(500),
    -- «Нужно внимание оператора»: истёк срок без автоматического решения
    -- (готовка затянулась, курьер не найден). Заказ не отменяется — еда
    -- уже готовится, — но попадает в очередь оператора (ADM-3, REL-6)
    attention_reason      VARCHAR(200),
    attention_at          TIMESTAMPTZ,
    -- Оптимистичная блокировка: кухня жмёт «готово», клиент — «отмена»,
    -- проигравшая операция получает конфликт версии и перечитывает заказ
    version               INTEGER NOT NULL DEFAULT 1,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (total_amount = items_amount + delivery_fee + service_fee - discount_amount),
    CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL AND cancel_reason IS NOT NULL)),
    CHECK ((attention_reason IS NULL) = (attention_at IS NULL))
);

-- Повторная отправка формы тем же клиентом с тем же ключом — тот же заказ
CREATE UNIQUE INDEX IF NOT EXISTS ux_orders_idempotency_key
    ON orders (customer_id, idempotency_key);

-- История заказов клиента (ORD-7)
CREATE INDEX IF NOT EXISTS ix_orders_customer_placed
    ON orders (customer_id, placed_at DESC);

-- Очередь кухни (KIT-1)
CREATE INDEX IF NOT EXISTS ix_orders_restaurant_status
    ON orders (restaurant_id, status);

-- Активные заказы: терминальных в индексе нет, поэтому он не растёт с историей
CREATE INDEX IF NOT EXISTS ix_orders_active
    ON orders (status)
    WHERE status NOT IN ('DELIVERED', 'CANCELLED');

-- Очередь оператора: только заказы, требующие внимания
CREATE INDEX IF NOT EXISTS ix_orders_attention
    ON orders (attention_at)
    WHERE attention_at IS NOT NULL;

-- ─────────────── Позиции заказа ───────────────
-- Снимки названия и цены на момент оформления: изменение меню задним числом
-- не должно переписывать историю заказов и чеки.
CREATE TABLE IF NOT EXISTS order_items (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id       UUID         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    position       SMALLINT     NOT NULL,
    menu_item_id   UUID         NOT NULL,
    name_snapshot  VARCHAR(200) NOT NULL,
    -- Базовая цена блюда за штуку; надбавки модификаторов — в order_item_options
    price_snapshot INTEGER      NOT NULL CHECK (price_snapshot >= 0),
    quantity       SMALLINT     NOT NULL CHECK (quantity > 0),
    -- (цена + надбавки) × количество
    line_total     INTEGER      NOT NULL CHECK (line_total >= 0),
    UNIQUE (order_id, position)
);

CREATE TABLE IF NOT EXISTS order_item_options (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_item_id        UUID         NOT NULL REFERENCES order_items (id) ON DELETE CASCADE,
    option_id            UUID         NOT NULL,
    name_snapshot        VARCHAR(200) NOT NULL,
    price_delta_snapshot INTEGER      NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_order_item_options_item ON order_item_options (order_item_id);

-- ─────────────── История статусов ───────────────
-- Экран оператора (ADM-3) и доказательство REL-6: видно, что ни один заказ
-- не застрял. Только добавление, строки не изменяются.
CREATE TABLE IF NOT EXISTS order_status_history (
    id          BIGSERIAL PRIMARY KEY,
    order_id    UUID        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    from_status VARCHAR(32),
    to_status   VARCHAR(32) NOT NULL,
    actor_type  VARCHAR(16) NOT NULL
                CHECK (actor_type IN ('CUSTOMER', 'RESTAURANT', 'COURIER',
                                      'OPERATOR', 'SYSTEM')),
    actor_id    VARCHAR(100),
    reason      VARCHAR(500),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_order_status_history_order
    ON order_status_history (order_id, id);

-- ─────────────── Сага оформления ───────────────
-- Оркестратор живёт в этом же сервисе: состояние саги и заказ меняются
-- в одной локальной транзакции.
CREATE TABLE IF NOT EXISTS order_sagas (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id     UUID        NOT NULL UNIQUE REFERENCES orders (id) ON DELETE CASCADE,
    current_step VARCHAR(32) NOT NULL,
    -- Что уже сделано у участников: захолдировано ли, списано ли, вызван ли
    -- курьер. По этим фактам выбираются компенсации
    state        JSONB       NOT NULL DEFAULT '{}'::jsonb,
    status       VARCHAR(16) NOT NULL DEFAULT 'RUNNING'
                 CHECK (status IN ('RUNNING', 'COMPENSATING', 'COMPLETED', 'FAILED')),
    started_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    version      INTEGER     NOT NULL DEFAULT 1
);

-- Число саг в компенсации — ключевая метрика дашборда
CREATE INDEX IF NOT EXISTS ix_order_sagas_unfinished
    ON order_sagas (status)
    WHERE status IN ('RUNNING', 'COMPENSATING');

-- Каждая попытка каждого шага, включая компенсации: по этой таблице
-- восстанавливается полный путь заказа (REL-5)
CREATE TABLE IF NOT EXISTS saga_steps (
    id              BIGSERIAL PRIMARY KEY,
    saga_id         UUID        NOT NULL REFERENCES order_sagas (id) ON DELETE CASCADE,
    step_name       VARCHAR(32) NOT NULL,
    is_compensation BOOLEAN     NOT NULL DEFAULT FALSE,
    status          VARCHAR(16) NOT NULL
                    CHECK (status IN ('STARTED', 'SUCCEEDED', 'FAILED')),
    attempt         SMALLINT    NOT NULL DEFAULT 1 CHECK (attempt > 0),
    request         JSONB,
    response        JSONB,
    error           TEXT,
    started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS ix_saga_steps_saga ON saga_steps (saga_id, id);

-- ─────────────── Отложенные шаги и таймеры саги ───────────────
-- Одна таблица на два вида записей. Таймер — срок нетерминального статуса
-- (REL-6, KIT-5). Отложенный шаг — вызов участника саги, который выполняет
-- фоновый процесс, а не запрос пользователя: запрос не ждёт платёжный сервис,
-- а шаг переживает перезапуск и повторяется после сбоя.
-- Всё это в базе, а не в памяти процесса: после перезапуска сервиса
-- висящие заказы не зависают навсегда.
CREATE TABLE IF NOT EXISTS saga_timers (
    id         BIGSERIAL PRIMARY KEY,
    saga_id    UUID        NOT NULL REFERENCES order_sagas (id) ON DELETE CASCADE,
    order_id   UUID        NOT NULL,
    timer_type VARCHAR(32) NOT NULL,
    fire_at    TIMESTAMPTZ NOT NULL,
    fired_at   TIMESTAMPTZ,
    -- Сколько раз запись брали в работу; по нему считается задержка повтора
    attempts   SMALLINT    NOT NULL DEFAULT 0,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Планировщик выбирает наступившие несработавшие записи. Сработавшие
-- в индекс не попадают, поэтому опрос дёшев при любом объёме таблицы.
CREATE INDEX IF NOT EXISTS ix_saga_timers_pending
    ON saga_timers (fire_at)
    WHERE fired_at IS NULL;

-- Не больше одной активной записи данного типа на заказ
CREATE UNIQUE INDEX IF NOT EXISTS ux_saga_timers_active
    ON saga_timers (order_id, timer_type)
    WHERE fired_at IS NULL;
