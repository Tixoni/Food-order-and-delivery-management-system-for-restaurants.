-- Контекст трассы у отложенных шагов саги (OBS-2). Продолжает 001_orders.sql.
--
-- Шаг ставится в запросе (оформление, отмена), а выполняется позже фоновым
-- исполнителем — без сохранённого контекста трасса рвалась бы на каждом
-- шаге. Здесь заголовки W3C Trace Context (traceparent, tracestate) той
-- трассы, в которой шаг поставлен: холд виден в трассе оформления, снятие
-- холда — в трассе отмены, списание и курьер — в трассе подтверждения
-- кухней. Пусто — трассировка выключена, шаг начнёт новую трассу.

ALTER TABLE saga_timers ADD COLUMN IF NOT EXISTS trace_context JSONB;
