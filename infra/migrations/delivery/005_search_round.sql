-- Раунд поиска курьера. Продолжает 004_dropoff_contact.sql.
--
-- Курьер, который отказался или промолчал, не получает тот же заказ
-- повторно в этом раунде — иначе предложение ходило бы по кругу. Но когда
-- order повторяет запрос после «курьер не найден», начинается новый раунд,
-- и предлагать снова можно всем: курьер мог просто не заметить первое
-- предложение. Найдено на живой проверке: при одном курьере рядом заказ
-- навсегда оставался «не найден».

ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS search_started_at TIMESTAMPTZ;
UPDATE deliveries SET search_started_at = created_at WHERE search_started_at IS NULL;
